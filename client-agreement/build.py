"""Renders agreement_source.py into:
  - client-agreement/out/wordpress-page.html   (paste/publish as the WP page body)
  - vercel-endpoints/agreement-text.js         (copy to <vercel project>/lib/agreement-text.js)
Run:  python client-agreement/build.py
"""
import html, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import agreement_source as A  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT_DIR = os.path.join(HERE, 'out')
os.makedirs(OUT_DIR, exist_ok=True)

SIGN_URL = 'https://milesmaneric.github.io/milesman-crm/client-agreement-sign.html'


def esc(s):
    return html.escape(s, quote=False)


def para_html(p):
    # Lead-in label ("Award booking.") rendered bold when a short sentence
    # ending in a period starts the paragraph and the paragraph is longer.
    if re.match(r'^\([a-z]\) ', p):
        return '<p class="mm-sub">%s</p>' % esc(p)
    m = re.match(r'^([A-Z][A-Za-z0-9 ,\-/]{2,60}\.) (.+)$', p, flags=re.S)
    if m and len(m.group(2)) > 40 and m.group(1).count(' ') <= 8:
        return '<p><strong>%s</strong> %s</p>' % (esc(m.group(1)), esc(m.group(2)))
    return '<p>%s</p>' % esc(p)


def build_wp():
    parts = []
    parts.append('<!-- wp:html -->')
    parts.append('''<style>
.mm-agr{max-width:820px;margin:0 auto;line-height:1.65}
.mm-agr h2{font-size:1.2em;margin:1.8em 0 .5em}
.mm-agr p{margin:0 0 .85em}
.mm-agr .mm-sub{margin-left:1.6em}
.mm-agr .mm-meta{background:#f3f6fb;border:1px solid #d6e0ee;border-radius:10px;padding:14px 18px;font-size:.95em;margin:0 0 1.5em}
.mm-agr .mm-sign{margin-top:2.4em;padding-top:1.2em;border-top:2px solid #d6e0ee}
</style>''')
    parts.append('<div class="mm-agr">')
    parts.append('<div class="mm-meta"><strong>%s</strong><br>%s<br>Version %s. Please read this agreement, then sign it online at the bottom of this page. You only need to sign once; it covers every trip and service we provide.</div>'
                 % (esc(A.TITLE), esc(A.COMPANY), esc(A.VERSION)))
    for heading, paras in A.SECTIONS:
        parts.append('<h2>%s</h2>' % esc(heading))
        for p in paras:
            parts.append(para_html(p))
    parts.append('<div class="mm-sign" id="sign-online">')
    parts.append('<h2>Sign Online</h2>')
    parts.append('<p>%s</p>' % esc(A.ACKNOWLEDGMENT))
    parts.append('''<div id="milesman-agr-wrap"><iframe id="milesman-agr-frame" title="Sign the Miles Man Client Services Agreement" src="%s" style="width:100%%;height:1100px;border:none;"></iframe><script>
(function(){
  var f = document.getElementById('milesman-agr-frame');
  var qs = window.location.search;
  if (qs) { f.src = f.src + qs; }
})();
window.addEventListener('message', function(e){
  var d = e.data;
  if (!d) return;
  if (d.type === 'milesman-agr-height') {
    var f = document.getElementById('milesman-agr-frame');
    if (f) { f.style.height = d.height + 'px'; }
    return;
  }
  if (d.type === 'milesman-agr-scroll-top') {
    var s = document.getElementById('sign-online');
    if (s) { s.scrollIntoView({ behavior: 'smooth', block: 'start' }); }
  }
});
</script></div>''' % SIGN_URL)
    parts.append('<p style="font-size:.9em;color:#666">Questions before you sign? Call (908)&nbsp;419-7700 or email eric@themilesman.com. If you would rather have a paper copy, just ask.</p>')
    parts.append('</div>')
    parts.append('</div>')
    parts.append('<!-- /wp:html -->')
    out = '\n'.join(parts)
    # house rules for inline WP scripts: ASCII only, no double ampersand
    bad = [c for c in out if ord(c) > 126]
    assert not bad, 'non-ascii in WP output: %r' % bad[:5]
    assert '&&' not in out
    open(os.path.join(OUT_DIR, 'wordpress-page.html'), 'w', encoding='ascii', newline='\n').write(out)
    return out


def build_js():
    data = {
        'VERSION': A.VERSION,
        'TITLE': A.TITLE,
        'COMPANY': A.COMPANY,
        'ACK': A.ACKNOWLEDGMENT,
        'SECTIONS': [{'heading': h, 'paras': p} for h, p in A.SECTIONS],
    }
    js = ('// GENERATED by client-agreement/build.py from agreement_source.py - do not edit by hand.\n'
          'module.exports = %s;\n' % json.dumps(data, indent=1, ensure_ascii=True))
    open(os.path.join(ROOT, 'vercel-endpoints', 'agreement-text.js'), 'w', encoding='ascii', newline='\n').write(js)


def sync_sign_page():
    # Keeps the version literals in the signing page equal to VERSION.
    path = os.path.join(ROOT, 'client-agreement-sign.html')
    t = open(path, encoding='utf8', newline='').read()
    t = re.sub(r'(<span id="ver-label">)[^<]*(</span>)', r'\g<1>%s\g<2>' % A.VERSION, t)
    t = re.sub(r"(var VERSION = ')[^']*(';)", r'\g<1>%s\g<2>' % A.VERSION, t)
    open(path, 'w', encoding='utf8', newline='').write(t)


if __name__ == '__main__':
    build_wp()
    build_js()
    sync_sign_page()
    words = sum(len(p.split()) for _, ps in A.SECTIONS for p in ps)
    print('built v%s, %d sections, ~%d words' % (A.VERSION, len(A.SECTIONS), words))
